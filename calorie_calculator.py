def get_float_input(prompt):
    """Функция для безопасного ввода чисел с проверкой на ошибки"""
    while True:
        try:
            return float(input(prompt))
        except ValueError:
            print("⚠️ Ошибка: пожалуйста, введите число.")

def main():
    print("=" * 45)
    print("🍎 ДОБРО ПОЖАЛОВАТЬ В КАЛЬКУЛЯТОР КАЛОРИЙ 🍎")
    print("=" * 45)

    # 1. Ввод пола
    while True:
        gender = input("Введите ваш пол (м/ж): ").strip().lower()
        if gender in ['м', 'ж']:
            break
        print("Пожалуйста, введите 'м' или 'ж'.")

    # 2. Ввод параметров
    age = get_float_input("Введите ваш возраст (лет): ")
    weight = get_float_input("Введите ваш вес (кг): ")
    height = get_float_input("Введите ваш рост (см): ")

    # 3. Расчет базового обмена веществ (BMR) по формуле Миффлина-Сан Жеора
    if gender == 'м':
        bmr = 10 * weight + 6.25 * height - 5 * age + 5
    else:
        bmr = 10 * weight + 6.25 * height - 5 * age - 161

    # 4. Выбор уровня активности
    print("\n🏃 Выберите ваш уровень активности:")
    print("1. Минимальный (сидячий образ жизни)          - 1.2")
    print("2. Низкий (легкие тренировки 1-3 раза/нед)     - 1.375")
    print("3. Средний (тренировки 3-5 раз/нед)            - 1.55")
    print("4. Высокий (интенсивные тренировки 6-7 раз/нед)- 1.725")
    print("5. Очень высокий (тяжелая работа + тренировки) - 1.9")

    activity_map = {
        '1': 1.2, '2': 1.375, '3': 1.55, '4': 1.725, '5': 1.9
    }

    while True:
        choice = input("Введите номер варианта (1-5): ").strip()
        if choice in activity_map:
            break
        print("⚠️ Пожалуйста, введите число от 1 до 5.")

    activity_factor = activity_map[choice]
    
    # 5. Расчет суточной нормы (TDEE)
    tdee = bmr * activity_factor

    # 6. Вывод результатов
    print("\n" + "=" * 45)
    print("📊 ВАШИ РЕЗУЛЬТАТЫ")
    print("=" * 45)
    print(f"🔥 Базовый обмен веществ (BMR): {bmr:.0f} ккал")
    print(f"⚖️  Для поддержания веса:       {tdee:.0f} ккал")
    print(f"📉 Для безопасного похудения:   {tdee * 0.8:.0f} ккал (дефицит 20%)")
    print(f"📈 Для набора мышечной массы:   {tdee * 1.2:.0f} ккал (профицит 20%)")
    print("=" * 45)
    print("💡 Совет: Пейте достаточно воды и не забывайте про белок!")

if __name__ == "__main__":
    main()